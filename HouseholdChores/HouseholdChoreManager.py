class Chore:
    def __init__(self):
        self.choreName = ""
        self.category = ""
        self.frequency = ""
        self.location = ""
    def append(self, choreName, category, frequency, location):
        self.choreName = choreName
        self.category = category
        self.frequency = frequency
        self.location = location
    def printChore(self):
        print("Chore Name:", self.choreName)
        print("Category:", self.category)
        print("Frequency:", self.frequency)
        print("Location:", self.location)
    def getName(self):
        return self.choreName

class Assignment:
    def __init__(self):
        self.choreName = ""
        self.person = ""
        self.date = ""
        self.status = "Pending"
    def append(self, choreName, person, date):
        self.choreName = choreName
        self.person = person
        self.date = date
    def printAssignment(self):
        print("Chore:", self.choreName)
        print("Assigned To:", self.person)
        print("Date:", self.date)
        print("Status:", self.status)
    def getChoreName(self):
        return self.choreName
    def markCompleted(self):
        self.status = "Completed"

def add_chore():
    choreName = input("Chore Name: ")
    category = input("Category (Cleaning/Cooking/etc.): ")
    frequency = input("Frequency (Daily/Weekly/etc.): ")
    location = input("Location: ")
    chore = Chore()
    chore.append(choreName, category, frequency, location)
    chores.append(chore)
    print("Chore added successfully!")

def view_chores():
    if len(chores) == 0:
        print("\nNo chores in the record.")
        return
    print("\n====== HOUSEHOLD CHORES ======")
    for i in range(len(chores)):
        print("\nChore", i + 1)
        print("--------------------")
        chores[i].printChore()

def search_chore():
    if len(chores) == 0:
        print("\nNo chores in the record.")
        return
    name = input("Enter chore name: ")
    found = 0
    for i in range(len(chores)):
        if chores[i].getName().lower() == name.lower():
            print("\nChore found!")
            print("--------------------")
            chores[i].printChore()
            found = 1
    if found == 0:
        print("\nChore not found!")

def assign_chore():
    if len(chores) == 0:
        print("\nPlease add a chore first.")
        return
    choreName = input("Enter chore name: ")
    found = 0
    for i in range(len(chores)):
        if chores[i].getName().lower() == choreName.lower():
            person = input("Assign To: ")
            date = input("Date: ")
            assignment = Assignment()
            assignment.append(chores[i].getName(), person, date)
            assignments.append(assignment)
            print("Chore assigned successfully!")
            found = 1
            break
    if found == 0:
        print("\nChore not found!")

def view_assignments():
    if len(assignments) == 0:
        print("\nNo chore assignments.")
        return
    print("\n====== CHORE ASSIGNMENTS ======")
    for i in range(len(assignments)):
        print("\nAssignment", i + 1)
        print("--------------------")
        assignments[i].printAssignment()

def search_assignment():
    if len(assignments) == 0:
        print("\nNo chore assignments.")
        return
    choreName = input("Enter chore name: ")
    found = 0
    for i in range(len(assignments)):
        if assignments[i].getChoreName().lower() == choreName.lower():
            print("\nAssignment found!")
            print("--------------------")
            assignments[i].printAssignment()
            found = 1
    if found == 0:
        print("\nNo assignment found for this chore.")

def complete_chore():
    if len(assignments) == 0:
        print("\nNo chore assignments.")
        return
    view_assignments()
    choice = int(input("\nEnter assignment number to complete: "))
    if choice >= 1 and choice <= len(assignments):
        assignments[choice - 1].markCompleted()
        print("Chore marked as completed!")
    else:
        print("Invalid assignment number.")

def delete_chore():
    if len(chores) == 0:
        print("\nNo chores in the record.")
        return
    view_chores()
    choice = int(input("\nEnter chore number to remove: "))
    if choice >= 1 and choice <= len(chores):
        chores.pop(choice - 1)
        print("Chore removed successfully!")
    else:
        print("Invalid chore number.")


