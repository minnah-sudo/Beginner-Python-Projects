class Item:
    def __init__(self):
        self.itemName = ""
        self.category = ""
        self.location = ""
        self.date = ""
        self.owner = ""
    def append(self, itemName, category, location, date, owner):
        self.itemName = itemName
        self.category = category
        self.location = location
        self.date = date
        self.owner = owner
    def printItem(self):
        print("Item Name:", self.itemName)
        print("Category:", self.category)
        print("Location:", self.location)
        print("Date:", self.date)
        print("Owner:", self.owner)
    def getName(self):
        return self.itemName

class Report:
    def __init__(self):
        self.itemName = ""
        self.reportType = ""
        self.location = ""
        self.date = ""
        self.status = "Open"
    def append(self, itemName, reportType, location, date):
        self.itemName = itemName
        self.reportType = reportType
        self.location = location
        self.date = date
    def printReport(self):
        print("Item:", self.itemName)
        print("Report Type:", self.reportType)
        print("Location:", self.location)
        print("Date:", self.date)
        print("Status:", self.status)
    def getItemName(self):
        return self.itemName
    def closeReport(self):
        self.status = "Matched"

def add_item():
    itemName = input("Item Name: ")
    category = input("Category: ")
    location = input("Location: ")
    date = input("Date: ")
    owner = input("Owner Name: ")
    item = Item()
    item.append(itemName, category, location, date, owner)
    items.append(item)
    print("Item added successfully!")

def view_items():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    print("\n====== LOST & FOUND ITEMS ======")
    for i in range(len(items)):
        print("\nItem", i + 1)
        print("--------------------")
        items[i].printItem()

def search_item():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    name = input("Enter item name: ")
    found = 0
    for i in range(len(items)):
        if items[i].getName().lower() == name.lower():
            print("\nItem found!")
            print("--------------------")
            items[i].printItem()
            found = 1
    if found == 0:
        print("\nItem not found!")

def add_report():
    if len(items) == 0:
        print("\nPlease add an item first.")
        return
    itemName = input("Enter item name: ")
    found = 0
    for i in range(len(items)):
        if items[i].getName().lower() == itemName.lower():
            reportType = input("Report Type (Lost/Found): ")
            location = input("Location: ")
            date = input("Date: ")
            report = Report()
            report.append(items[i].getName(), reportType, location, date)
            reports.append(report)
            print("Report added successfully!")
            found = 1
            break
    if found == 0:
        print("\nItem not found!")

def view_reports():
    if len(reports) == 0:
        print("\nNo reports in the system.")
        return
    print("\n====== LOST & FOUND REPORTS ======")
    for i in range(len(reports)):
        print("\nReport", i + 1)
        print("--------------------")
        reports[i].printReport()

def search_report():
    if len(reports) == 0:
        print("\nNo reports in the system.")
        return
    itemName = input("Enter item name: ")
    found = 0
    for i in range(len(reports)):
        if reports[i].getItemName().lower() == itemName.lower():
            print("\nReport found!")
            print("--------------------")
            reports[i].printReport()
            found = 1
    if found == 0:
        print("\nNo report found for this item.")

def match_items():
    if len(reports) < 2:
        print("\nAt least two reports are needed to find a match.")
        return
    lostItem = input("Enter lost item name: ")
    foundItem = input("Enter found item name: ")
    lostFound = 0
    foundFound = 0
    lostIndex = -1
    foundIndex = -1
    for i in range(len(reports)):
        if reports[i].getItemName().lower() == lostItem.lower():
            if reports[i].reportType.lower() == "lost":
                lostFound = 1
                lostIndex = i
        if reports[i].getItemName().lower() == foundItem.lower():
            if reports[i].reportType.lower() == "found":
                foundFound = 1
                foundIndex = i
    if lostFound == 1 and foundFound == 1:
        print("Lost Item:", reports[lostIndex].itemName)
        print("Found Item:", reports[foundIndex].itemName)
        reports[lostIndex].closeReport()
        reports[foundIndex].closeReport()
        print("Both reports have been marked as Matched.")
    else:
        print("\nNo matching lost and found reports were found.")

def delete_item():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    view_items()
    choice = int(input("\nEnter item number to remove: "))
    if choice >= 1 and choice <= len(items):
        items.pop(choice - 1)
        print("Item removed successfully!")
    else:
        print("Invalid item number.")


