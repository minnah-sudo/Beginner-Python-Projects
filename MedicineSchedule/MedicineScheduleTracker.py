def delete_medicines():
    view_medicines()
    if len(medicines) == 0:
        return
    choice = int(input("Enter medicine number to remove: "))
    if choice >= 1 and choice <= len(medicines):
        medicines.pop(choice - 1)
        print("Removed Successfully!")
    else:
        print("Invalid medicine number.")

def change_status():
    view_medicines()
    if len(medicines) == 0:
        return
    choice = int(input("Enter medicine number that was taken: "))
    if choice >= 1 and choice <= len(medicines):
        medicines[choice - 1].changeToTaken()
        print("Medicine marked as taken!")
    else:
        print("Invalid medicine number.")

