class InvoiceItem:#invoice generator for a business
    def __init__(self):
        self.itemName = ""
        self.quantity = 0
        self.price = 0
        self.category = ""

    def append(self, name, qty, price, category):
        self.itemName = name
        self.quantity = qty
        self.price = price
        self.category = category

    def printItem(self):
        print("Item:", self.itemName)
        print("Category:", self.category)
        print("Quantity:", self.quantity)
        print("Price per item:", self.price)
        print("Item Total:", self.getTotal())

    def getName(self):
        return self.itemName

    def getTotal(self):
        return self.quantity * self.price

def add_item():
    name = input("Item Name: ")
    category = input("Category: ")
    quantity = int(input("Quantity: "))
    price = float(input("Price per item: "))
    item = InvoiceItem()
    item.append(name, quantity, price, category)
    invoiceItems.append(item)
    print("Item added successfully!")


def view_items():
    if len(invoiceItems) == 0:
        print("\nNo items in the invoice.")
        return
    print("\n====== INVOICE ITEMS ======")
    for i in range(len(invoiceItems)):
        print("\nItem", i + 1)
        print("--------------------")
        invoiceItems[i].printItem()


def search_item():
    if len(invoiceItems) == 0:
        print("\nNo items in the invoice.")
        return
    name = input("Enter item name: ")
    found = 0
    for i in range(len(invoiceItems)):
        if invoiceItems[i].getName().lower() == name.lower():
            print("\nItem found!")
            print("--------------------")
            invoiceItems[i].printItem()
            found = 1
    if found == 0:
        print("\nItem not found!")


def delete_item():
    if len(invoiceItems) == 0:
        print("\nNo items in the invoice.")
        return
    view_items()
    choice = int(input("\nEnter item number to remove: "))
    if choice >= 1 and choice <= len(invoiceItems):
        invoiceItems.pop(choice - 1)
        print("Item removed successfully!")
    else:
        print("Invalid item number.")


def calculate_subtotal():
    subtotal = 0
    for i in range(len(invoiceItems)):
        subtotal = subtotal + invoiceItems[i].getTotal()
    print("\nSubtotal:", subtotal)


def calculate_tax():
    subtotal = 0
    for i in range(len(invoiceItems)):
        subtotal = subtotal + invoiceItems[i].getTotal()
    taxRate = float(input("Enter tax percentage: "))
    tax = subtotal * taxRate / 100
    print("Tax:", tax)


def calculate_total():
    subtotal = 0
    for i in range(len(invoiceItems)):
        subtotal = subtotal + invoiceItems[i].getTotal()
    taxRate = float(input("Enter tax percentage: "))
    tax = subtotal * taxRate / 100
    total = subtotal + tax
    print("\n====== INVOICE TOTAL ======")
    print("Subtotal:", subtotal)
    print("Tax:", tax)
    print("Final Total:", total)



