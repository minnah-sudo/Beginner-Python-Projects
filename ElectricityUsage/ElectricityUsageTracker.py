class Appliance:
    def __init__(self):
        self.name = ""
        self.power = 0
        self.hours = 0
        self.days = 0
    def append(self, name, power, hours, days):
        self.name = name
        self.power = power
        self.hours = hours
        self.days = days
    def printAppliance(self):
        print("Appliance:", self.name)
        print("Power:", self.power, "Watts")
        print("Hours Used Per Day:", self.hours)
        print("Days Used:", self.days)
        print("Energy Used:", self.getEnergy(), "kWh")
    def getName(self):
        return self.name
    def getEnergy(self):
        # Convert Watts to Kilowatts
        powerInKW = self.power / 1000
        # Energy = Power × Time
        energy = powerInKW * self.hours * self.days
        return energy

def add_appliance():
    name = input("Appliance Name: ")
    power = float(input("Power of appliance (Watts): "))
    hours = float(input("Hours used per day: "))
    days = int(input("Number of days used: "))
    appliance = Appliance()
    appliance.append(name, power, hours, days)
    appliances.append(appliance)
    print("Appliance added successfully!")

def view_appliances():
    if len(appliances) == 0:
        print("\nNo appliances in the record.")
        return
    print("\n====== ELECTRICITY USAGE RECORDS ======")
    for i in range(len(appliances)):
        print("\nAppliance", i + 1)
        print("--------------------")
        appliances[i].printAppliance()

def search_appliance():
    if len(appliances) == 0:
        print("\nNo appliances in the record.")
        return
    name = input("Enter appliance name: ")
    found = 0
    for i in range(len(appliances)):
        if appliances[i].getName().lower() == name.lower():
            print("\nAppliance found!")
            print("--------------------")
            appliances[i].printAppliance()
            found = 1
    if found == 0:
        print("\nAppliance not found!")

def delete_appliance():
    if len(appliances) == 0:
        print("\nNo appliances in the record.")
        return
    view_appliances()
    choice = int(input("\nEnter appliance number to remove: "))
    if choice >= 1 and choice <= len(appliances):
        appliances.pop(choice - 1)
        print("Appliance removed successfully!")
    else:
        print("Invalid appliance number.")

def calculate_appliance_usage():
    if len(appliances) == 0:
        print("\nNo appliances in the record.")
        return
    name = input("Enter appliance name: ")
    found = 0
    for i in range(len(appliances)):
        if appliances[i].getName().lower() == name.lower():
            print("\nAppliance:", appliances[i].getName())
            print("Estimated Energy Usage:", appliances[i].getEnergy(), "kWh")
            found = 1
    if found == 0:
        print("\nAppliance not found!")

def calculate_total_usage():
    if len(appliances) == 0:
        print("\nNo appliances in the record.")
        return
    total = 0
    for i in range(len(appliances)):
        total = total + appliances[i].getEnergy()
    print("\n====== TOTAL ENERGY USAGE ======")
    print("Estimated Energy Usage:", total, "kWh")


