class BrokenItem:
    def __init__(self):
        self.itemName = ""
        self.category = ""
        self.problem = ""
        self.repairCost = 0
        self.replacementCost = 0
        self.status = "Not Decided"
    def append(self, itemName, category, problem, repairCost, replacementCost):
        self.itemName = itemName
        self.category = category
        self.problem = problem
        self.repairCost = repairCost
        self.replacementCost = replacementCost
    def printItem(self):
        print("Item Name:", self.itemName)
        print("Category:", self.category)
        print("Problem:", self.problem)
        print("Estimated Repair Cost:", self.repairCost)
        print("Replacement Cost:", self.replacementCost)
        print("Decision:", self.status)
    def getName(self):
        return self.itemName
    def compareCosts(self):
        if self.repairCost < self.replacementCost:
            print("Repairing the item costs less.")
            print("Estimated Savings:", self.replacementCost - self.repairCost)
        elif self.repairCost > self.replacementCost:
            print("Replacing the item costs less.")
            print("Estimated Difference:", self.repairCost - self.replacementCost)
        else:
            print("Both options have the same estimated cost.")
    def updateDecision(self, decision):
        self.status = decision

def add_item():
    itemName = input("Item Name: ")
    category = input("Category: ")
    problem = input("Describe the Problem: ")
    repairCost = float(input("Estimated Repair Cost: "))
    replacementCost = float(input("Replacement Cost: "))
    item = BrokenItem()
    item.append(itemName, category, problem, repairCost, replacementCost)
    items.append(item)
    print("Item added successfully!")

def view_items():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    print("\n====== BROKEN ITEMS ======")
    for i in range(len(items)):
        print("\nItem", i + 1)
        print("--------------------")
        items[i].printItem()

def search_item():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    name = input("Enter item name: ")
    found = 0
    for i in range(len(items)):
        if items[i].getName().lower() == name.lower():
            print("\nItem found!")
            print("--------------------")
            items[i].printItem()
            found = 1
    if found == 0:
        print("\nItem not found!")

def compare_costs():
    if len(items) == 0:
        print("\nNo items in the record.")
        return
    name = input("Enter item name: ")
    found = 0
    for i in range(len(items)):
        if items[i].getName().lower() == name.lower():
            print("\n====== COST COMPARISON ======")
            print("Item:", items[i].getName())
            print("Repair Cost:", items[i].repairCost)
            print("Replacement Cost:", items[i].replacementCost)
            items[i].compareCosts()
