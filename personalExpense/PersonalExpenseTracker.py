class Expense:#personal expense manager
    def __init__(self):
        self.title = ""
        self.category = ""
        self.amount = 0
        self.date = ""

    def append(self, title, category, amount, date):
        self.title = title
        self.category = category
        self.amount = amount
        self.date = date

    def printExpense(self):
        print("Title:", self.title)
        print("Category:", self.category)
        print("Amount:", self.amount)
        print("Date:", self.date)

    def getCategory(self):
        return self.category

    def getAmount(self):
        return self.amount

def add_expense():
    title = input("Expense Title: ")
    category = input("Category: ")
    amount = float(input("Amount: "))
    date = input("Date: ")
    expense = Expense()
    expense.append(title, category, amount, date)
    expenses.append(expense)
    print("Expense added successfully!")


def view_expenses():
    if len(expenses) == 0:
        print("\nNo expenses in the record.")
        return
    print("\n====== EXPENSE RECORDS ======")
    for i in range(len(expenses)):
        print("\nExpense", i + 1)
        print("--------------------")
        expenses[i].printExpense()


def search_expenses():
    if len(expenses) == 0:
        print("\nNo expenses in the record.")
        return
    category = input("Enter category to search: ")
    found = 0
    for i in range(len(expenses)):
        if expenses[i].getCategory().lower() == category.lower():
            print("\nExpense found!")
            print("--------------------")
            expenses[i].printExpense()
            found = 1
    if found == 0:
        print("\nNo expenses found in this category.")


def delete_expense():
    if len(expenses) == 0:
        print("\nNo expenses in the record.")
        return
    view_expenses()
    choice = int(input("\nEnter expense number to remove: "))
    if choice >= 1 and choice <= len(expenses):
        expenses.pop(choice - 1)
        print("Expense removed successfully!")
    else:
        print("Invalid expense number.")

def calculate_total():
    if len(expenses) == 0:
        print("\nNo expenses in the record.")
        return
    total = 0
    for i in range(len(expenses)):
        total = total + expenses[i].getAmount()
    print("\n====== TOTAL SPENDING ======")
    print("Total:", total)


expenses = []
while True:
    print("\n")
    print("================================")
    print("       PERSONAL EXPENSE TRACKER")
    print("================================")
    print("1. Add Expense")
    print("2. View Expenses")
    print("3. Search by Category")
    print("4. Delete Expense")
    print("5. Calculate Total Spending")
    print("6. Exit")
    choice = input("\nEnter choice: ")
    if choice == "1":
        add_expense()
    elif choice == "2":
        view_expenses()
    elif choice == "3":
        search_expenses()
    elif choice == "4":
        delete_expense()
    elif choice == "5":
        calculate_total()
    elif choice == "6":
        print("\nExiting Personal Expense Tracker...")
        break
    else:
        print("\nInvalid choice. Please try again.")