def view_lost_items():
    if len(lostItems) == 0:
        print("\nNo lost items in the record.")
        return
    print("\n====== LOST ITEMS ======")
    for i in range(len(lostItems)):
        print("\nLost Item", i + 1)
        print("--------------------")
        lostItems[i].printItem()

