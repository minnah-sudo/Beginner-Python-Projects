class Car:
    def __init__(self):
        self.carName = ""
        self.model = ""
        self.year = 0
        self.mileage = 0
    def append(self, carName, model, year, mileage):
        self.carName = carName
        self.model = model
        self.year = year
        self.mileage = mileage
    def printCar(self):
        print("Car Name:", self.carName)
        print("Model:", self.model)
        print("Year:", self.year)
        print("Mileage:", self.mileage, "km")
    def getName(self):
        return self.carName

class Service:
    def __init__(self):
        self.carName = ""
        self.serviceType = ""
        self.date = ""
        self.mileage = 0
        self.cost = 0
    def append(self, carName, serviceType, date, mileage, cost):
        self.carName = carName
        self.serviceType = serviceType
        self.date = date
        self.mileage = mileage
        self.cost = cost
    def printService(self):
        print("Car:", self.carName)
        print("Service Type:", self.serviceType)
        print("Date:", self.date)
        print("Mileage:", self.mileage, "km")
        print("Cost:", self.cost)
    def getCarName(self):
        return self.carName

def add_car():
    carName = input("Car Name: ")
    model = input("Car Model: ")
    year = int(input("Car Year: "))
    mileage = int(input("Current Mileage (km): "))
    car = Car()
    car.append(carName, model, year, mileage)
    cars.append(car)
    print("Car added successfully!")

def view_cars():
    if len(cars) == 0:
        print("\nNo cars in the record.")
        return
    print("\n====== CAR RECORDS ======")
    for i in range(len(cars)):
        print("\nCar", i + 1)
        print("--------------------")
        cars[i].printCar()

def search_car():
    if len(cars) == 0:
        print("\nNo cars in the record.")
        return
    name = input("Enter car name: ")
    found = 0
    for i in range(len(cars)):
        if cars[i].getName().lower() == name.lower():
            print("\nCar found!")
            print("--------------------")
            cars[i].printCar()
            found = 1
    if found == 0:
        print("\nCar not found!")

