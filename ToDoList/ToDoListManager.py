class Task:#to-do list manager
    def __init__(self):
        self.title = ""
        self.description = ""
        self.priority = ""
        self.dueDate = ""
        self.status = "Pending"

    def append(self, title, description, priority, dueDate):
        self.title = title
        self.description = description
        self.priority = priority
        self.dueDate = dueDate

    def printTask(self):
        print("Title:", self.title)
        print("Description:", self.description)
        print("Priority:", self.priority)
        print("Due Date:", self.dueDate)
        print("Status:", self.status)
    def getTitle(self):
        return self.title
    def markCompleted(self):
        self.status = "Completed"

def add_task():
    title = input("Task Title: ")
    description = input("Task Description: ")
    priority = input("Priority (High/Medium/Low): ")
    dueDate = input("Due Date: ")
    task = Task()
    task.append(title, description, priority, dueDate)
    tasks.append(task)
    print("Task added successfully!")

def view_tasks():
    if len(tasks) == 0:
        print("\nNo tasks in the list.")
        return
    print("\n====== TO-DO TASKS ======")
    for i in range(len(tasks)):
        print("\nTask", i + 1)
        print("--------------------")
        tasks[i].printTask()

def search_task():
    if len(tasks) == 0:
        print("\nNo tasks in the list.")
        return
    title = input("Enter task title: ")
    found = 0
    for i in range(len(tasks)):
        if tasks[i].getTitle().lower() == title.lower():
            print("\nTask found!")
            print("--------------------")
            tasks[i].printTask()
            found = 1
    if found == 0:
        print("\nTask not found!")


def delete_task():
    if len(tasks) == 0:
        print("\nNo tasks in the list.")
        return
    view_tasks()
    choice = int(input("\nEnter task number to remove: "))
    if choice >= 1 and choice <= len(tasks):
        tasks.pop(choice - 1)
        print("Task removed successfully!")
    else:
        print("Invalid task number.")


def complete_task():
    if len(tasks) == 0:
        print("\nNo tasks in the list.")
        return
    view_tasks()
    choice = int(input("\nEnter task number to mark as completed: "))
    if choice >= 1 and choice <= len(tasks):
        tasks[choice - 1].markCompleted()
        print("Task marked as completed!")
    else:
        print("Invalid task number.")


tasks = []
while True:
    print("\n")
    print("================================")
    print("          TO-DO MANAGER")
    print("================================")
    print("1. Add Task")
    print("2. View Tasks")
    print("3. Search Task")
    print("4. Delete Task")
    print("5. Mark Task as Completed")
    print("6. Exit")
    choice = input("\nEnter choice: ")
    if choice == "1":
        add_task()
    elif choice == "2":
        view_tasks()
    elif choice == "3":
        search_task()
    elif choice == "4":
        delete_task()
    elif choice == "5":
        complete_task()
    elif choice == "6":
        print("\nExiting To-Do Manager...")
        break
    else:
        print("\nInvalid choice. Please try again.")