class Medicine: # Each medicine has the following:
  def __init__(self):
    self.medicineName = "" # a name
    self.frequency = "" # how often it should be taken
    self.quantity = 0 # how many pills should be taken
    self.time = "" # what time it should be taken
    self.status = "Untaken"

  def append(self, name, freq, qty, tme):
    self.medicineName = name
    self.frequency = freq
    self.quantity = qty
    self.time = tme

  def printMedicine(self):
    print(self.medicineName)
    print("Frequency:", self.frequency)
    print("Quantity:", self.quantity)
    print("Time:", self.time)
    print("Status:",self.status)

  def getName(self):
     return self.medicineName

  def changeToTaken(self):
     self.status="Taken"

def add_medicine():
  name = input("Medicine Name: ")
  freq = input("Frequency: ")
  qty = int(input("Quantity of pills: "))
  time = input("Time: ")
  medicine = Medicine()
  medicine.append(name, freq, qty, time)
  medicines.append(medicine)

def view_medicines():
  print("\n====== MEDICINE SCHEDULE ======")
  for i in range(len(medicines)):
    print(i + 1)
    medicines[i].printMedicine()
    print()

