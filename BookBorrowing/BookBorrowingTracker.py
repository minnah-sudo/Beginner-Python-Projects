class Book:
    def __init__(self):
        self.title = ""
        self.author = ""
        self.category = ""
        self.year = 0
    def append(self, title, author, category, year):
        self.title = title
        self.author = author
        self.category = category
        self.year = year
    def printBook(self):
        print("Book Title:", self.title)
        print("Author:", self.author)
        print("Category:", self.category)
        print("Year:", self.year)
    def getTitle(self):
        return self.title

class BorrowRecord:
    def __init__(self):
        self.bookTitle = ""
        self.borrower = ""
        self.borrowDate = ""
        self.returnDate = ""
        self.status = "Borrowed"
    def append(self, bookTitle, borrower, borrowDate):
        self.bookTitle = bookTitle
        self.borrower = borrower
        self.borrowDate = borrowDate
    def printRecord(self):
        print("Book:", self.bookTitle)
        print("Borrower:", self.borrower)
        print("Borrow Date:", self.borrowDate)
        print("Return Date:", self.returnDate)
        print("Status:", self.status)
    def getBookTitle(self):
        return self.bookTitle
    def markReturned(self, returnDate):
        self.returnDate = returnDate
        self.status = "Returned"

def add_book():
    title = input("Book Title: ")
    author = input("Author: ")
    category = input("Category: ")
    year = int(input("Publication Year: "))
    book = Book()
    book.append(title, author, category, year)
    books.append(book)
    print("Book added successfully!")

def view_books():
    if len(books) == 0:
        print("\nNo books in the library.")
        return
    print("\n====== BOOK RECORDS ======")
    for i in range(len(books)):
        print("\nBook", i + 1)
        print("--------------------")
        books[i].printBook()

def search_book():
    if len(books) == 0:
        print("\nNo books in the library.")
        return
    title = input("Enter book title: ")
    found = 0
    for i in range(len(books)):
        if books[i].getTitle().lower() == title.lower():
            print("\nBook found!")
            print("--------------------")
            books[i].printBook()
            found = 1
    if found == 0:
        print("\nBook not found!")

def borrow_book():
    if len(books) == 0:
        print("\nNo books in the library.")
        return
    title = input("Enter book title: ")
    found = 0
    for i in range(len(books)):
        if books[i].getTitle().lower() == title.lower():
            # Check if this book is already borrowed
            alreadyBorrowed = 0
            for j in range(len(borrowRecords)):
                if borrowRecords[j].getBookTitle().lower() == title.lower():
                    if borrowRecords[j].status == "Borrowed":
                        alreadyBorrowed = 1
            if alreadyBorrowed == 1:
                print("\nThis book is already borrowed.")
                return
            borrower = input("Borrower Name: ")
            borrowDate = input("Borrow Date: ")
            record = BorrowRecord()
            record.append(books[i].getTitle(), borrower, borrowDate)
            borrowRecords.append(record)
            print("Book borrowed successfully!")
            found = 1
            break
    if found == 0:
        print("\nBook not found!")

def view_borrow_records():
    if len(borrowRecords) == 0:
        print("\nNo borrowing records.")
        return
    print("\n====== BORROWING RECORDS ======")
    for i in range(len(borrowRecords)):
        print("\nRecord", i + 1)
        print("--------------------")
        borrowRecords[i].printRecord()

def search_borrow_record():
    if len(borrowRecords) == 0:
        print("\nNo borrowing records.")
        return
    title = input("Enter book title: ")
    found = 0
    for i in range(len(borrowRecords)):
        if borrowRecords[i].getBookTitle().lower() == title.lower():
            print("\nBorrowing record found!")
            print("--------------------")
            borrowRecords[i].printRecord()
            found = 1
    if found == 0:
        print("\nNo borrowing record found for this book.")

def return_book():
    if len(borrowRecords) == 0:
        print("\nNo borrowing records.")
        return
    title = input("Enter book title to return: ")
    found = 0
    for i in range(len(borrowRecords)):
        if borrowRecords[i].getBookTitle().lower() == title.lower():
            if borrowRecords[i].status == "Borrowed":
                returnDate = input("Return Date: ")
                borrowRecords[i].markReturned(returnDate)
                print("Book returned successfully!")
                found = 1
                break
    if found == 0:
        print("\nNo active borrowing record found for this book.")

def delete_book():
    if len(books) == 0:
        print("\nNo books in the library.")
        return
    view_books()
    choice = int(input("\nEnter book number to remove: "))
    if choice >= 1 and choice <= len(books):
        books.pop(choice - 1)
        print("Book removed successfully!")
    else:
        print("Invalid book number.")


