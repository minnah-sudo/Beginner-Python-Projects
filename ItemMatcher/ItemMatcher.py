class LostItem:

    def __init__(self):
        self.itemName = ""
        self.category = ""
        self.color = ""
        self.location = ""
        self.date = ""
        self.owner = ""

    def append(self, itemName, category, color, location, date, owner):
        self.itemName = itemName
        self.category = category
        self.color = color
        self.location = location
        self.date = date
        self.owner = owner

    def printItem(self):
        print("Item Name:", self.itemName)
        print("Category:", self.category)
        print("Color:", self.color)
        print("Location:", self.location)
        print("Date Lost:", self.date)
        print("Owner:", self.owner)

    def getName(self):
        return self.itemName


class FoundItem:
    def __init__(self):
        self.itemName = ""
        self.category = ""
        self.color = ""
        self.location = ""
        self.date = ""
        self.finder = ""
        self.status = "Available"
    def append(self, itemName, category, color, location, date, finder):
        self.itemName = itemName
        self.category = category
        self.color = color
        self.location = location
        self.date = date
        self.finder = finder
    def printItem(self):
        print("Item Name:", self.itemName)
        print("Category:", self.category)
        print("Color:", self.color)
        print("Location:", self.location)
        print("Date Found:", self.date)
        print("Finder:", self.finder)
        print("Status:", self.status)
    def getName(self):
        return self.itemName
    def markReturned(self):
        self.status = "Returned"

def add_lost_item():
    itemName = input("Item Name: ")
    category = input("Category: ")
    color = input("Color: ")
    location = input("Location where it was lost: ")
    date = input("Date Lost: ")
    owner = input("Owner Name: ")
    item = LostItem()
