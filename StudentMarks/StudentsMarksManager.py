class Student:#students marks mangaer
    def __init__(self):
        self.name = ""
        self.rollNumber = ""
        self.english = 0
        self.math = 0
        self.computer = 0
        self.science = 0

    def append(self, name, roll, english, math, computer, science):
        self.name = name
        self.rollNumber = roll
        self.english = english
        self.math = math
        self.computer = computer
        self.science = science

    def printStudent(self):
        print("Name:", self.name)
        print("Roll Number:", self.rollNumber)
        print("English:", self.english)
        print("Math:", self.math)
        print("Computer:", self.computer)
        print("Science:", self.science)
        print("Total:", self.getTotal())
        print("Percentage:", round(self.getPercentage(), 2))
        print("Grade:", self.getGrade())

    def getName(self):
        return self.name

    def getTotal(self):
        return self.english + self.math + self.computer + self.science

    def getPercentage(self):
        return (self.getTotal() / 400) * 100

    def getGrade(self):
        percentage = self.getPercentage()
        if percentage >= 80:
            return "A"
        elif percentage >= 70:
            return "B"
        elif percentage >= 60:
            return "C"
        elif percentage >= 50:
            return "D"
        else:
            return "F"


def add_student():
    name = input("Student Name: ")
    roll = input("Roll Number: ")
    english = int(input("English Marks: "))
    math = int(input("Math Marks: "))
    computer = int(input("Computer Marks: "))
    science = int(input("Science Marks: "))
    student = Student()
    student.append(name, roll, english, math, computer, science)
    students.append(student)
    print("Student added successfully!")


def view_students():
    if len(students) == 0:
        print("\nNo students in the record.")
        return
    print("\n====== STUDENT RECORDS ======")
    for i in range(len(students)):
        print("\nStudent", i + 1)
        print("--------------------")
        students[i].printStudent()


def search_student():
    if len(students) == 0:
        print("\nNo students in the record.")
        return
    name = input("Enter student name: ")
    found = 0
    for i in range(len(students)):
        if students[i].getName().lower() == name.lower():
            print("\nStudent found!")
            print("--------------------")
            students[i].printStudent()
            found = 1
    if found == 0:
        print("\nStudent not found!")

def delete_student():
    if len(students) == 0:
        print("\nNo students in the record.")
        return
    view_students()
    choice = int(input("\nEnter student number to remove: "))
    if choice >= 1 and choice <= len(students):
        students.pop(choice - 1)
        print("Student removed successfully!")
    else:
        print("Invalid student number.")



